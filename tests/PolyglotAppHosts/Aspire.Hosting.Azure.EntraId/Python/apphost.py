from aspire_app import create_builder

with create_builder() as builder:
    tenant = builder.add_parameter("tenant")
    client = builder.add_parameter("client")
    secret = builder.add_parameter("secret", secret=True)
    owner = builder.add_parameter("owner")
    redirect = builder.add_parameter("redirect")
    host = builder.add_parameter("host")
    identity_id = "00000000-0000-0000-0000-000000000001"

    existing = builder.add_existing_entra_app("existing", "contoso.onmicrosoft.com", identity_id)
    parameterized = builder.add_existing_entra_app_from_parameters("parameterized", tenant, client)
    existing.with_client_secret(secret)
    existing.with_instance("https://login.microsoftonline.us/")
    existing.with_sign_in_audience("AzureADMultipleOrgs")
    existing.with_federated_managed_identity_credential(identity_id)
    existing.with_certificate_from_key_vault("https://example.vault.azure.net", "certificate")
    existing.with_certificate_thumbprint("CurrentUser/My", "0123456789ABCDEF")
    existing.with_certificate_distinguished_name("CurrentUser/My", "CN=example")
    existing.with_client_capability("cp1")
    existing.with_allow_web_api_to_be_authorized_by_acl()
    existing.with_send_x5_c()
    existing.with_extra_query_parameter("domain_hint", "contoso.com")
    existing.with_audience("api://example")
    existing.with_credential(builder.create_entra_id_file_certificate_credential("/certs/client.pfx", password=secret))
    existing.with_credential(builder.create_entra_id_signed_assertion_file_credential())
    parameterized.with_credential(builder.create_entra_id_signed_assertion_file_credential(file_path="/tokens/assertion"))
    existing.with_credential(builder.create_entra_id_federated_identity_credential(
        identity_id, token_exchange_url="api://AzureADTokenExchange",
        token_exchange_authority="https://login.microsoftonline.com/contoso.onmicrosoft.com"))

    web = builder.add_container("web", "nginx").with_http_endpoint(target_port=80)
    web.with_reference(existing)
    web.with_entra_id_reference(parameterized, connection_name="Identity")
    created = builder.add_entra_id_app("created")
    created.with_redirect_uris(["https://localhost:7123/signin-oidc"])
    created.with_redirect_uris_from_parameters([redirect])
    created.with_redirect_uris_for_endpoint(web.get_endpoint("http"), ["/signin-oidc"])
    created.with_redirect_uris_for_host(host, "/signin-oidc", ["/signout-callback-oidc"])
    created.with_app_owners([identity_id])
    created.with_app_owners_from_parameters([owner])
    created.with_service_principal_owners([identity_id])
    created.with_service_principal_owners_from_parameters([owner])
    created.with_owners([identity_id])
    created.with_owners_from_parameters([owner])
    created.with_id_token_issuance()
    created.publish_with_federated_managed_identity_credential()
    web.with_reference(created)
    targeted = builder.add_entra_id_app("targeted")
    web.with_reference(targeted)
    targeted.publish_with_federated_managed_identity_credential(identity=web)
    identity = builder.add_azure_user_assigned_identity("identity")
    shared = builder.add_entra_id_app("shared")
    shared.publish_with_federated_managed_identity_credential(identity=identity)
    web.with_azure_user_assigned_identity(identity).with_reference(shared)
    builder.add_entra_id_app("converted").as_existing_app("contoso.onmicrosoft.com", identity_id)
    builder.add_entra_id_app("converted-parameters").as_existing_app_from_parameters(tenant, client)
    builder.run()
