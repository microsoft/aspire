using System.Globalization;
using System.Text;
using System.Text.Json;
using Aspire.Cli.Configuration;
using Aspire.Cli.Interaction;
using Aspire.Cli.Resources;
using Aspire.Hosting.Utils;
using Spectre.Console;

namespace Aspire.Cli.Agents;

/// <summary>
/// A skill named in the generated agent instructions, with the one-line job an agent picks it for.
/// </summary>
internal sealed record AgentInstructionsSkill(string Name, string Job);

/// <summary>
/// How <see cref="AgentInstructionsFile.WriteAsync"/> changed the agent instructions file.
/// </summary>
internal enum AgentInstructionsFileChange
{
    Created,
    Appended,
    Updated,
    Unchanged,

    /// <summary>
    /// The file has a start marker without a matching end marker, so the extent of the
    /// Aspire section is unknown and the file is left untouched.
    /// </summary>
    SkippedMalformedSection
}

/// <summary>
/// Writes the Aspire section of the <c>AGENTS.md</c> file that <c>aspire new</c> and
/// <c>aspire agent init</c> place beside the <c>aspire.config.json</c> of an Aspire application.
/// </summary>
/// <remarks>
/// <para>
/// Coding agents read <c>AGENTS.md</c> on every turn without any plugin, skill or MCP setup
/// (https://agents.md). The section gives the start flow for this AppHost in order: start it, list
/// its resources with <c>aspire describe</c>, then <c>aspire wait</c> on the ones the task needs.
/// It deliberately carries no skill content; skills are delivered through agent plugins.
/// </para>
/// <para>
/// An existing file is never overwritten. The Aspire section is delimited by HTML comment markers,
/// which markdown renderers hide: when the file has no section, one is appended after the existing
/// content; when it has one, only the text between the markers is replaced, so a later
/// <c>aspire agent init</c> can add the skills it installed to the section <c>aspire new</c> wrote.
/// </para>
/// </remarks>
internal static class AgentInstructionsFile
{
    internal const string FileName = "AGENTS.md";

    // Matching uses only the marker prefixes so the explanatory text after them can change
    // without orphaning sections written by earlier CLIs.
    internal const string SectionStartMarkerPrefix = "<!-- aspire:begin";
    internal const string SectionEndMarkerPrefix = "<!-- aspire:end";

    private const string SectionStartMarker = SectionStartMarkerPrefix +
        " (generated by the Aspire CLI; `aspire new` and `aspire agent init` replace the text up to aspire:end) -->";
    private const string SectionEndMarker = SectionEndMarkerPrefix + " -->";

    /// <summary>
    /// The skills of the <c>aspire@aspire-skills</c> plugin, with the job each one is picked for.
    /// The plugin content is acquired by the agent, not the CLI, so this list mirrors
    /// https://github.com/microsoft/aspire-skills/blob/main/.github/plugins/aspire-skills/.claude-plugin/plugin.json
    /// and must be updated when that plugin adds, renames or removes a skill.
    /// </summary>
    internal static IReadOnlyList<AgentInstructionsSkill> AspireSkillsPluginSkills { get; } =
    [
        new("aspire", "route an Aspire task to the right Aspire skill."),
        new("aspire-orchestration", "start, stop and restart the app and its resources, and fix start-up failures."),
        new("aspire-monitoring", "logs, traces, metrics and resource state of a running app; the standalone dashboard."),
        new("aspireify", "wire resources into an AppHost."),
        new("aspire-init", "add Aspire to a repository."),
        new("aspire-deployment", "deploy or publish the app."),
        new("aspire-terminals", "author and automate Aspire terminals."),
        new("aspire-project-v2-migration", "move project resources to the v2 APIs.")
    ];

    /// <summary>
    /// Reads the AppHost path that the <c>aspire.config.json</c> in <paramref name="directory"/> configures.
    /// </summary>
    /// <returns>The full AppHost path, or <see langword="null"/> when no AppHost is configured or the file can't be read.</returns>
    internal static string? GetConfiguredAppHostPath(DirectoryInfo directory)
    {
        try
        {
            if (AspireConfigFile.Load(directory.FullName)?.AppHost?.Path is { Length: > 0 } path)
            {
                // Stored paths use '/' separators on every platform and are relative to the config file.
                return Path.GetFullPath(path.Replace('\\', Path.DirectorySeparatorChar).Replace('/', Path.DirectorySeparatorChar), directory.FullName);
            }
        }
        catch (Exception ex) when (ex is JsonException or IOException or UnauthorizedAccessException)
        {
            // An unreadable config file only means the start flow can't be described; template creation
            // and agent setup report the config problem themselves when they need the file.
        }

        return null;
    }

    /// <summary>
    /// Creates the Aspire section, including its markers, without a trailing line break.
    /// </summary>
    /// <param name="appHostPath">The AppHost path relative to the directory of the instructions file.</param>
    /// <param name="skills">The installed skills to list, or an empty list when none are known.</param>
    /// <param name="newLine">The line break to use.</param>
    internal static string CreateSection(string appHostPath, IReadOnlyList<AgentInstructionsSkill> skills, string newLine)
    {
        // Commands are copied verbatim by agents, so a path with spaces must be quoted to stay one argument.
        var appHostArgument = appHostPath.Any(char.IsWhiteSpace) ? $"\"{appHostPath}\"" : appHostPath;
        var builder = new StringBuilder();
        void Line(string text = "") => builder.Append(text).Append(newLine);

        Line(SectionStartMarker);
        Line("## Aspire");
        Line();
        Line($"This is an Aspire application. Its AppHost is `{appHostPath}`.");
        Line();
        Line("### Run it");
        Line($"1. Start it: `aspire start --apphost {appHostArgument} --non-interactive --isolated`.");
        Line("2. `aspire describe` lists every resource of the running app with its state, health and endpoint");
        Line("   URLs. That list names the resources to wait on.");
        Line("3. `aspire wait <resource-name>` for each resource the task needs, with `<resource-name>` taken from");
        Line("   that list. It returns when the resource is healthy.");
        Line();
        Line("`aspire logs <resource-name>` prints that resource's console output.");
        Line();
        Line("### When it is slow");
        Line("Start with `aspire otel traces -n 15 --search \"duration:>500\"` (milliseconds; lower the");
        Line("threshold if nothing comes back), before reading code or timing requests by hand.");

        if (skills.Count > 0)
        {
            Line();
            Line("### Skills");
            foreach (var skill in skills)
            {
                Line($"- `{skill.Name}`: {skill.Job}");
            }
        }

        builder.Append(SectionEndMarker);
        return builder.ToString();
    }

    /// <summary>
    /// Creates <c>AGENTS.md</c> in <paramref name="directory"/>, or adds or refreshes its Aspire section.
    /// </summary>
    /// <param name="directory">The directory that receives the file.</param>
    /// <param name="appHostPath">The full path of the AppHost the start flow targets.</param>
    /// <param name="skills">The installed skills to list.</param>
    /// <param name="cancellationToken">A cancellation token.</param>
    internal static async Task<AgentInstructionsFileChange> WriteAsync(
        DirectoryInfo directory,
        string appHostPath,
        IReadOnlyList<AgentInstructionsSkill> skills,
        CancellationToken cancellationToken)
    {
        // Agents run the commands from the directory holding AGENTS.md, so the path is relative to it.
        // Forward slashes work in every shell the commands are pasted into.
        var relativeAppHostPath = PathNormalizer.NormalizePathForStorage(Path.GetRelativePath(directory.FullName, appHostPath));
        var filePath = Path.Combine(directory.FullName, FileName);

        if (!File.Exists(filePath))
        {
            var newLine = Environment.NewLine;
            var content = $"# Agent instructions{newLine}{newLine}{CreateSection(relativeAppHostPath, skills, newLine)}{newLine}";
            await WriteFileAsync(filePath, content, FileMode.CreateNew, cancellationToken);
            return AgentInstructionsFileChange.Created;
        }

        var existing = await File.ReadAllTextAsync(filePath, cancellationToken);
        var lineBreak = existing.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var section = CreateSection(relativeAppHostPath, skills, lineBreak);

        var start = existing.IndexOf(SectionStartMarkerPrefix, StringComparison.Ordinal);
        if (start < 0)
        {
            var separator = existing.Length == 0
                ? string.Empty
                : existing.EndsWith('\n') ? lineBreak : lineBreak + lineBreak;
            await WriteFileAsync(filePath, existing + separator + section + lineBreak, FileMode.Create, cancellationToken);
            return AgentInstructionsFileChange.Appended;
        }

        var endMarker = existing.IndexOf(SectionEndMarkerPrefix, start, StringComparison.Ordinal);
        if (endMarker < 0)
        {
            return AgentInstructionsFileChange.SkippedMalformedSection;
        }

        // The section ends with the end marker line; the line break after it belongs to the user's content.
        var end = existing.IndexOf('\n', endMarker);
        end = end < 0 ? existing.Length : existing[end - 1] == '\r' ? end - 1 : end;
        var updated = string.Concat(existing.AsSpan(0, start), section, existing.AsSpan(end));
        if (string.Equals(updated, existing, StringComparison.Ordinal))
        {
            return AgentInstructionsFileChange.Unchanged;
        }

        await WriteFileAsync(filePath, updated, FileMode.Create, cancellationToken);
        return AgentInstructionsFileChange.Updated;
    }

    /// <summary>
    /// Writes the file like <see cref="WriteAsync"/> and reports the change to the user.
    /// </summary>
    /// <returns><see langword="false"/> when the file could not be written.</returns>
    internal static async Task<bool> WriteAndReportAsync(
        IInteractionService interactionService,
        DirectoryInfo directory,
        string appHostPath,
        IReadOnlyList<AgentInstructionsSkill> skills,
        CancellationToken cancellationToken)
    {
        var displayPath = Path.Combine(directory.FullName, FileName).EscapeMarkup();
        AgentInstructionsFileChange change;
        try
        {
            change = await WriteAsync(directory, appHostPath, skills, cancellationToken);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            interactionService.DisplayError(string.Format(CultureInfo.CurrentCulture,
                SharedCommandStrings.AgentInstructionsFileWriteFailed, displayPath, ex.Message.EscapeMarkup()));
            return false;
        }

        switch (change)
        {
            case AgentInstructionsFileChange.Created:
                interactionService.DisplayMessage(KnownEmojis.PageFacingUp, string.Format(CultureInfo.CurrentCulture,
                    SharedCommandStrings.AgentInstructionsFileCreated, displayPath));
                break;
            case AgentInstructionsFileChange.Appended:
                interactionService.DisplayMessage(KnownEmojis.PageFacingUp, string.Format(CultureInfo.CurrentCulture,
                    SharedCommandStrings.AgentInstructionsFileAppended, displayPath));
                break;
            case AgentInstructionsFileChange.Updated:
                interactionService.DisplayMessage(KnownEmojis.PageFacingUp, string.Format(CultureInfo.CurrentCulture,
                    SharedCommandStrings.AgentInstructionsFileUpdated, displayPath));
                break;
            case AgentInstructionsFileChange.SkippedMalformedSection:
                interactionService.DisplayMessage(KnownEmojis.PoliceCarLight, string.Format(CultureInfo.CurrentCulture,
                    SharedCommandStrings.AgentInstructionsFileSkippedMalformedSection, displayPath, SectionEndMarker.EscapeMarkup()));
                break;
        }

        return true;
    }

    private static async Task WriteFileAsync(string filePath, string content, FileMode mode, CancellationToken cancellationToken)
    {
        await using var stream = new FileStream(filePath, mode, FileAccess.Write, FileShare.None);
        await using var writer = new StreamWriter(stream, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        await writer.WriteAsync(content.AsMemory(), cancellationToken);
    }
}
